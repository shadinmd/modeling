"""
Agent reasoning loop with real-time tool execution and pluggable LLMs.
"""

import os
import re
import sys
from typing import Dict, List, Optional

from llm import BaseLLMClient, HuggingFaceLocalClient, OpenAICompatibleClient
from tools import AssistantTools


class PersonalAgent:
    """Agent runtime: works completely independently with ANY local or remote model."""

    def __init__(self, llm_client: Optional[BaseLLMClient] = None, backend: str = "hf", model_id: str = "LiquidAI/LFM3-1.7B"):
        self.tools = AssistantTools()

        if llm_client is not None:
            self.llm = llm_client
        elif backend == "lmstudio":
            self.llm = OpenAICompatibleClient(base_url="http://localhost:1234/v1", model_name=model_id)
        elif backend == "ollama":
            self.llm = OpenAICompatibleClient(base_url="http://localhost:11434/v1", model_name=model_id)
        else:
            self.llm = HuggingFaceLocalClient(model_id=model_id)

    def _parse_and_execute_tools(self, response: str) -> Optional[str]:
        """Detect tool calls in either custom XML tags or structured tags generated by LFM3/ChatML."""
        # 1. read_file call (supports both <tool_call:read_file path="..."> and XML block format)
        match_read = re.search(r'<tool_call:read_file\s+path=["\']([^"\']+)["\']\s*\/?>', response)
        if not match_read:
            match_read = re.search(r'<function=tool_call:read_file>\s*<parameter=path>\s*([^\s<]+)\s*<\/parameter>', response, re.DOTALL)
        if not match_read:
            match_read = re.search(r'read_file\(\s*["\']([^"\']+)["\']\s*\)', response)

        if match_read:
            path = match_read.group(1).strip()
            print(f"\n[Agent Action] Reading real file from disk: {path}...")
            content = self.tools.read_file(path)
            return f"[Tool Output: Content of '{path}']\n{content}"

        # 2. search_notes call
        match_search = re.search(r'<tool_call:search\s+query=["\']([^"\']+)["\']\s*\/?>', response)
        if not match_search:
            match_search = re.search(r'<function=tool_call:search>\s*<parameter=query>\s*([^\s<]+)\s*<\/parameter>', response, re.DOTALL)
        if match_search:
            query = match_search.group(1).strip()
            print(f"\n[Agent Action] Searching notes for: '{query}'...")
            matches = self.tools.search_notes(query)
            return f"[Tool Output: Search Results for '{query}']\n{matches}"

        # 3. add_fact call
        match_fact = re.search(r'<tool_call:add_fact\s+fact=["\']([^"\']+)["\']\s*\/?>', response)
        if not match_fact:
            match_fact = re.search(r'<function=tool_call:add_fact>\s*<parameter=fact>\s*([^<]+)\s*<\/parameter>', response, re.DOTALL)
        if match_fact:
            fact = match_fact.group(1).strip()
            print(f"\n[Agent Action] Saving new fact to memory: '{fact}'...")
            res = self.tools.add_quick_fact(fact)
            return f"[Tool Output: Memory Update]\n{res}"

        return None

    def chat_turn(self, user_query: str, history: Optional[List[Dict[str, str]]] = None) -> str:
        """Execute one complete user turn with automatic agent tool reflection."""
        system_prompt = self.tools.get_system_context()

        messages = [{"role": "system", "content": system_prompt}]
        if history:
            messages.extend(history)
        messages.append({"role": "user", "content": user_query})

        # First pass generation
        response = self.llm.generate(messages, stream=False)

        # Check if agent invoked a tool call
        tool_result = self._parse_and_execute_tools(response)

        if tool_result:
            # Re-feed real-time file content back to agent for final grounded answer
            messages.append({"role": "assistant", "content": response})
            messages.append({"role": "user", "content": f"{tool_result}\nNow provide the final answer to my question based on this file."})
            print("\nAssistant > ", end="", flush=True)
            final_response = self.llm.generate(messages, stream=True)
            return final_response

        # If no tool called, print response
        print(response)
        return response
